import jsPDF from 'jspdf';

/**
 * Generate a downloadable executive PDF report from analysis results.
 */
export async function downloadAnalysisPdf(analysis, candidateName = 'Applicant') {
  if (!analysis) return;

  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 20;

  // Header Banner
  doc.setFillColor(15, 23, 42); // Deep navy #0F172A
  doc.rect(0, 0, pageWidth, 30, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('ResumeAI – Smart ATS Evaluation Report', 15, 18);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(148, 163, 184); // Slate 400
  doc.text(`Generated: ${new Date().toLocaleDateString()} | File: ${analysis.filename || 'resume.pdf'}`, 15, 25);

  y = 40;

  // 1. Overall Score Section
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text('1. OVERALL ATS COMPATIBILITY SCORE', 15, y);

  y += 8;
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(15, y, pageWidth - 30, 24, 3, 3, 'F');

  doc.setFontSize(22);
  doc.setTextColor(79, 70, 229); // Brand indigo
  doc.text(`${Math.round(analysis.overall_score || 0)} / 100`, 22, y + 16);

  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.setFont('helvetica', 'normal');
  doc.text(
    'Estimated compatibility calculated across 6 weighted ATS pillars supported by AI evaluation.',
    75,
    y + 14
  );

  y += 34;

  // 2. Category Scores Breakdown
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.text('2. CATEGORY-WISE ATS BREAKDOWN', 15, y);
  y += 7;

  const categories = [
    { label: 'Skills Relevance (Max 25)', score: analysis.category_scores?.skills_relevance || 0 },
    { label: 'Experience Quality (Max 20)', score: analysis.category_scores?.experience_quality || 0 },
    { label: 'Keyword Optimization (Max 20)', score: analysis.category_scores?.keyword_optimization || 0 },
    { label: 'Resume Structure (Max 15)', score: analysis.category_scores?.resume_structure || 0 },
    { label: 'Readability & Layout (Max 10)', score: analysis.category_scores?.readability || 0 },
    { label: 'Education Relevance (Max 10)', score: analysis.category_scores?.education_relevance || 0 },
  ];

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  categories.forEach((cat) => {
    doc.setTextColor(71, 85, 105);
    doc.text(`• ${cat.label}:`, 20, y);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(15, 23, 42);
    doc.text(`${cat.score} pts`, 120, y);
    doc.setFont('helvetica', 'normal');
    y += 6;
  });

  y += 6;

  // 3. Key Strengths
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(16, 185, 129); // Emerald
  doc.text('3. KEY STRENGTHS', 15, y);
  y += 7;

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(51, 65, 85);
  (analysis.strengths || []).forEach((st) => {
    const lines = doc.splitTextToSize(`✓ ${st}`, pageWidth - 35);
    doc.text(lines, 20, y);
    y += lines.length * 5;
  });

  y += 4;

  // 4. Areas for Optimization (Weaknesses)
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(225, 29, 72); // Rose
  doc.text('4. AREAS FOR OPTIMIZATION', 15, y);
  y += 7;

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(51, 65, 85);
  (analysis.weaknesses || []).forEach((wk) => {
    const lines = doc.splitTextToSize(`! ${wk}`, pageWidth - 35);
    doc.text(lines, 20, y);
    y += lines.length * 5;
  });

  // Check page overflow
  if (y > 230) {
    doc.addPage();
    y = 20;
  } else {
    y += 6;
  }

  // 5. Strategic AI Recommendations
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(79, 70, 229);
  doc.text('5. STRATEGIC AI RECOMMENDATIONS', 15, y);
  y += 7;

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(51, 65, 85);
  (analysis.recommendations || []).forEach((rec, idx) => {
    const lines = doc.splitTextToSize(`${idx + 1}. ${rec}`, pageWidth - 35);
    doc.text(lines, 20, y);
    y += lines.length * 5;
  });

  // Footer Disclaimer
  y = Math.min(280, y + 10);
  doc.setFontSize(7.5);
  doc.setTextColor(148, 163, 184);
  doc.text(
    'DISCLAIMER: This ATS score is an estimated compatibility indicator calculated via rule-based metrics and AI evaluation.',
    15,
    y
  );
  doc.text('Generated by ResumeAI • www.resumeai.io', 15, y + 4);

  // Save the PDF
  const safeFilename = (analysis.filename || 'resume').replace(/\.[^/.]+$/, '');
  doc.save(`${safeFilename}_ATS_Report.pdf`);
}
